// ---- flatten + state ----
const grid = document.getElementById('grid');
const chipsEl = document.getElementById('chips');
const emptyEl = document.getElementById('empty');
const searchEl = document.getElementById('search');
const randomBtn = document.getElementById('randomBtn');

let activeCategory = 'All';
let showUsedOnly = false;
let showUnusedOnly = false;

const STORAGE_KEY = 'ea-fact-vault-used';
function getUsedSet(){
  try{
    return new Set(JSON.parse(localStorage.getItem(STORAGE_KEY) || '[]'));
  }catch(e){ return new Set(); }
}
function saveUsedSet(set){
  try{
    localStorage.setItem(STORAGE_KEY, JSON.stringify([...set]));
  }catch(e){ /* storage unavailable, ignore */ }
}
let usedSet = getUsedSet();

const flat = [];
Object.keys(factsData).forEach(cat => {
  factsData[cat].forEach((text, i) => {
    const prefix = cat.slice(0,3).toUpperCase();
    flat.push({ id: `${prefix}-${String(i+1).padStart(2,'0')}`, category: cat, text });
  });
});

document.getElementById('totalStat').textContent = `${flat.length} FACTS`;
document.getElementById('catStat').textContent = `${Object.keys(factsData).length} CATEGORIES`;

function updateUsedStat(){
  document.getElementById('usedStat').textContent = `${usedSet.size} USED`;
}
updateUsedStat();

function buildChips(){
  const cats = ['All', ...Object.keys(factsData)];
  let html = cats.map(c =>
    `<button class="chip${c===activeCategory?' active':''}" data-cat="${c}">${c}</button>`
  ).join('');
  html += `<button class="chip used-filter${showUnusedOnly?' active':''}" data-special="unused">Unused only</button>`;
  html += `<button class="chip used-filter${showUsedOnly?' active':''}" data-special="used">Used only</button>`;
  chipsEl.innerHTML = html;

  chipsEl.querySelectorAll('.chip[data-cat]').forEach(btn => {
    btn.addEventListener('click', () => {
      activeCategory = btn.dataset.cat;
      buildChips();
      render();
    });
  });
  chipsEl.querySelectorAll('.chip[data-special]').forEach(btn => {
    btn.addEventListener('click', () => {
      if(btn.dataset.special === 'unused'){
        showUnusedOnly = !showUnusedOnly;
        showUsedOnly = false;
      } else {
        showUsedOnly = !showUsedOnly;
        showUnusedOnly = false;
      }
      buildChips();
      render();
    });
  });
}

function matchesFilters(f, q){
  const matchesCat = activeCategory === 'All' || f.category === activeCategory;
  const matchesQ = !q || f.text.toLowerCase().includes(q) || f.category.toLowerCase().includes(q);
  const isUsed = usedSet.has(f.id);
  const matchesUsedFilter = showUsedOnly ? isUsed : (showUnusedOnly ? !isUsed : true);
  return matchesCat && matchesQ && matchesUsedFilter;
}

function render(highlightId){
  const q = searchEl.value.trim().toLowerCase();
  const filtered = flat.filter(f => matchesFilters(f, q));

  if(filtered.length === 0){
    grid.innerHTML = '';
    emptyEl.style.display = 'block';
    return;
  }
  emptyEl.style.display = 'none';

  grid.innerHTML = filtered.map(f => {
    const isUsed = usedSet.has(f.id);
    return `
    <div class="fact-card${f.id===highlightId?' pulse':''}${isUsed?' is-used':''}" data-id="${f.id}" id="card-${f.id}">
      <div>
        <div class="card-top">
          <div class="card-id">${f.id}</div>
        </div>
        <div class="card-text">${f.text}</div>
      </div>
      <div class="card-bottom">
        <div class="card-tag">${f.category}</div>
        <div class="card-actions">
          <button class="icon-btn copy-btn" data-text="${f.text.replace(/"/g,'&quot;')}">Copy</button>
          <button class="icon-btn used-btn${isUsed?' used':''}" data-id="${f.id}">${isUsed ? 'Used ✓' : 'Mark used'}</button>
        </div>
      </div>
    </div>
  `;
  }).join('');

  grid.querySelectorAll('.copy-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      navigator.clipboard.writeText(btn.dataset.text).then(() => {
        const old = btn.textContent;
        btn.textContent = 'Copied!';
        setTimeout(() => { btn.textContent = old; }, 1200);
      }).catch(() => {});
    });
  });

  grid.querySelectorAll('.used-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const id = btn.dataset.id;
      if(usedSet.has(id)) usedSet.delete(id); else usedSet.add(id);
      saveUsedSet(usedSet);
      updateUsedStat();
      render();
    });
  });

  if(highlightId){
    const el = document.getElementById(`card-${highlightId}`);
    if(el) el.scrollIntoView({behavior:'smooth', block:'center'});
  }
}

searchEl.addEventListener('input', () => render());

randomBtn.addEventListener('click', () => {
  const q = searchEl.value.trim().toLowerCase();
  const pool = flat.filter(f => matchesFilters(f, q));
  if(pool.length === 0) return;
  const pick = pool[Math.floor(Math.random() * pool.length)];
  render(pick.id);
});

buildChips();
render();
